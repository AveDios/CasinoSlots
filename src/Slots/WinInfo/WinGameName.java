package Slots.WinInfo;

/**
 * Represents the types of slot machine games available in the system.
 * Used to identify the specific game associated with a win condition.
 *
 * @author AveDios
 * @since 1.0
 */
public enum WinGameName {

    /**
     * Represents a two-dimensional slot machine game with a 3x5 board.
     */
    TWO_DIMENSIONAL_SLOTS,

    /**
     * Represents a one-dimensional slot machine game with a single row of five slots.
     */
    ONE_DIMENSIONAL_SLOTS
}
