package Slots.WinInfo;

/**
 * Represents the possible win conditions based on the number of matching symbols in a one-dimensional slot machine game.
 * Used to determine the payout multiplier for a winning combination.
 */
public enum WinPossibilities {

    /**
     * Represents a win with three matching symbols.
     */
    THREE,

    /**
     * Represents a win with four matching symbols.
     */
    FOUR,

    /**
     * Represents a win with five matching symbols.
     */
    FIVE
}



